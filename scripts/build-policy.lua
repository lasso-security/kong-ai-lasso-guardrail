-- Builds ai-gateway/handler.lua: the single-file handler Kong AI Gateway 2.x streams as a
-- custom policy. A streamed policy is exactly schema.lua + handler.lua, so the plugin's local
-- modules (lasso.lua, client.lua) can't be required; they are inlined here instead.
--
--   lua scripts/build-policy.lua           write ai-gateway/handler.lua
--   lua scripts/build-policy.lua --check   fail if ai-gateway/handler.lua is stale (CI)

local SRC = "kong/plugins/ai-lasso-guardrail/"
local OUT = "ai-gateway/handler.lua"

local function read(path)
  local f = assert(io.open(path, "rb"))
  local s = f:read("*a")
  f:close()
  return s
end

local function inline(src, module, file)
  local line = 'local ' .. module .. ' = require "kong.plugins.ai-lasso-guardrail.' .. module .. '"'
  local i, j = src:find(line, 1, true)
  assert(i, "require line not found in handler.lua: " .. line)
  local body = read(SRC .. file)
  return src:sub(1, i - 1)
    .. "local " .. module .. " = (function()\n-- ── inlined from " .. SRC .. file .. " ──\n"
    .. body .. "end)()" .. src:sub(j + 1)
end

local out = read(SRC .. "handler.lua")
out = inline(out, "lasso", "lasso.lua")
out = inline(out, "client", "client.lua")
out = "-- GENERATED by scripts/build-policy.lua. Do not edit: change " .. SRC .. "*.lua and rebuild.\n"
  .. "-- Kong AI Gateway 2.x streaming custom policy handler (register with " .. SRC .. "schema.lua).\n\n"
  .. out

if arg[1] == "--check" then
  local ok, current = pcall(read, OUT)
  if not ok or current ~= out then
    io.stderr:write(OUT .. " is stale: run `lua scripts/build-policy.lua` and commit the result\n")
    os.exit(1)
  end
  print(OUT .. " is up to date")
else
  local f = assert(io.open(OUT, "wb"))
  f:write(out)
  f:close()
  print("wrote " .. OUT)
end
